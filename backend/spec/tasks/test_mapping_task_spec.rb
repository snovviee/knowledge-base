require "rails_helper"

# features/29_test_mapping. `bin/rails test_mapping:write` writes specs/docs/test_mapping.md, and
# `bin/rails test_mapping:check` checks that it is current (spec question 1). The tasks run in the
# test process (spec/support/rake_helpers.rb), on fixture repositories built by
# spec/support/test_mapping_fixtures.rb, so no line of this file looks like a test.
RSpec.describe "test_mapping:write and test_mapping:check", type: :task do
  include_context "test mapping fixtures"

  def mapping
    root.join("specs/docs/test_mapping.md")
  end

  # Every file and folder under the root, each file with its content and its time of change.
  def snapshot
    Dir.glob("**/*", File::FNM_DOTMATCH, base: root).sort.to_h do |path|
      file = root.join(path)
      [ path, file.file? ? [ file.read, file.mtime ] : :folder ]
    end
  end

  it "AC-29 test_mapping:write writes specs/docs/test_mapping.md and prints the counts" do
    write_requirements("AC-01" => "Sign in with Google", "AC-02" => "Sign in with GitHub")
    write_spec(
      "backend/spec/requests/sign_in_spec.rb",
      rspec_test("AC-01 signs in with Google"),
      rspec_test("AC-01 AC-02 signs in with either provider"),
      rspec_test("AC-02 is skipped", keyword: "xit")
    )
    write_vitest("frontend/src/App.test.tsx", vitest_test("AC-01 shows the Google button"), vitest_test("AC-02 shows it"))

    out, err, status = run_task("test_mapping:write")

    expect(out).to eq("Wrote specs/docs/test_mapping.md: 2 backend tests, 2 frontend tests.\n")
    expect(err).to eq("")
    expect(status).to eq(0)
    written = mapping.read
    expect(written).to eq(TestMapping.text)
    expect(written).to start_with("Generated by `bin/rails test_mapping:write`")

    expect(run_task("test_mapping:write")).to eq([ out, "", 0 ])
    expect(mapping.read).to eq(written)
  end

  it "AC-29 test_mapping:check passes on a current mapping and changes no file" do
    write_requirements("AC-01" => "Sign in with Google", "AC-02" => "Sign in with GitHub")
    write_spec("backend/spec/requests/sign_in_spec.rb", rspec_test("AC-01 signs in with Google"))
    run_task("test_mapping:write")
    expect(mapping.read).to include("| [AC-02](#ac-02) | Sign in with GitHub | 0 | 0 | Not covered |")
    files = snapshot

    out, err, status = run_task("test_mapping:check")

    expect(out).to eq("Test mapping check passed: specs/docs/test_mapping.md is current.\n")
    expect(err).to eq("")
    expect(status).to eq(0)
    expect(snapshot).to eq(files)
  end

  it "AC-29 test_mapping:check fails on a stale or missing mapping, names the parts that differ, and passes after test_mapping:write" do
    write_requirements("AC-01" => "Sign in with Google", "AC-02" => "Sign in with GitHub", "AC-03" => "Create the user")
    google = rspec_test("AC-01 signs in with Google")
    github = rspec_test("AC-02 signs in with GitHub")
    write_spec("backend/spec/requests/sign_in_spec.rb", google, github)
    write_plan("03_user_auto_create", results: [ [ "Pass, 2026-11-09." ] ])
    stale = ->(parts) {
      "Test mapping check failed:\n" \
        "- specs/docs/test_mapping.md is out of date in: #{parts}. Run bin/rails test_mapping:write.\n"
    }
    # Runs the check, expects it to fail with the message and to change no file, and writes the mapping
    # again, after which the check passes.
    expect_stale = ->(message) {
      files = snapshot
      expect(run_task("test_mapping:check")).to eq([ "", message, 1 ])
      expect(snapshot).to eq(files)
      run_task("test_mapping:write")
      expect(run_task("test_mapping:check")).to eq([ "Test mapping check passed: specs/docs/test_mapping.md is current.\n", "", 0 ])
    }

    expect_stale.call("Test mapping check failed:\n- specs/docs/test_mapping.md does not exist. Run bin/rails test_mapping:write.\n")

    write_spec("backend/spec/requests/sign_in_spec.rb", google, github, rspec_test("AC-02 shows the name"))
    expect_stale.call(stale.call("the summary, AC-02"))

    write_spec("backend/spec/requests/sign_in_spec.rb", rspec_test("AC-01 signs in with a Google account"), github, rspec_test("AC-02 shows the name"))
    expect_stale.call(stale.call("AC-01"))

    write_spec("backend/spec/requests/sign_in_spec.rb", github)
    expect_stale.call(stale.call("the summary, AC-01, AC-02"))

    write_plan("03_user_auto_create", results: [ [ "Pass, 2026-11-09.", "Fail, 2026-11-10. It broke." ] ])
    expect_stale.call(stale.call("the summary, AC-03"))

    parts = mapping.read.split(/^(?=## )/)
    ac_01 = parts.index { |part| part.start_with?("## AC-01\n") }
    parts[ac_01], parts[ac_01 + 1] = parts[ac_01 + 1], parts[ac_01]
    mapping.write(parts.join)
    expect(mapping.read.scan(/^## AC-0\d$/)).to eq([ "## AC-02", "## AC-01", "## AC-03" ])
    expect_stale.call(stale.call("AC-01, AC-02"))

    write_spec("backend/spec/requests/sign_in_spec.rb", github, rspec_test("has no AC ID", keyword: "xit"))
    expect(run_task("test_mapping:check")[1]).to include(
      "- specs/docs/test_mapping.md is out of date in: Tests with no known AC. Run bin/rails test_mapping:write.\n"
    )
  end

  it "AC-29 test_mapping:check fails while a test has no known AC and names it" do
    write_requirements("AC-01" => "Sign in with Google")
    write_spec(
      "backend/spec/models/mapping_probe_spec.rb",
      rspec_test("AC-99 probe with an unknown AC"),
      rspec_test("probe with no AC"),
      rspec_test('AC-01 probe with #{interpolation}'),
      rspec_test("AC-01 signs in")
    )
    write_vitest("frontend/src/MappingProbe.test.ts", vitest_test("AC-31 probe"))
    run_task("test_mapping:write")

    out, err, status = run_task("test_mapping:check")

    expect(out).to eq("")
    expect(err).to eq(
      "Test mapping check failed:\n" \
        "- A test has no known AC: backend/spec/models/mapping_probe_spec.rb: \"AC-99 probe with an unknown AC\".\n" \
        "- A test has no known AC: backend/spec/models/mapping_probe_spec.rb: \"probe with no AC\".\n" \
        "- A test has no known AC: backend/spec/models/mapping_probe_spec.rb: `it \"AC-01 probe with \#{interpolation}\" do`.\n" \
        "- A test has no known AC: frontend/src/MappingProbe.test.ts: \"AC-31 probe\".\n"
    )
    expect(status).to eq(1)
  end

  it "AC-29 test_mapping:check fails when the README's Test coverage table names a test that does not exist" do
    write_requirements("AC-01" => "Sign in with Google", "AC-13" => "Mark a note as reviewed")
    write_spec(
      "backend/spec/requests/sign_in_spec.rb",
      rspec_test("AC-01 signs in with Google"),
      rspec_test('AC-01 shows \"Ada | Lovelace\" as the name'),
      rspec_test("AC-01 is skipped for now", keyword: "xit")
    )
    write_vitest("frontend/src/App.test.tsx", vitest_test("AC-01 shows the Google button"))
    sign_in_spec = "`backend/spec/requests/sign_in_spec.rb`"
    readme = ->(heading, *rows) {
      write_file(
        "README.md",
        "# Personal Knowledge Base",
        "",
        "## Specification",
        "",
        heading,
        "",
        "```bash",
        "# a comment in a code block is not a heading",
        "docker compose run --rm backend bin/rails test_mapping:check",
        "```",
        "",
        "| Case (requirements.md 7) | AC | Tests |",
        "|---|---|---|",
        *rows,
        "",
        "## Running locally",
        "",
        "| A table after the section | AC-01 | #{sign_in_spec}: \"AC-01 is not in Test coverage\" |"
      )
    }
    readme.call(
      "### Test coverage",
      "| SSO login success path | AC-01 | #{sign_in_spec}: \"AC-01 signs in with Google\"<br>" \
        "`frontend/src/App.test.tsx`: \"AC-01 shows the Google button\" |",
      "| A name with a quote and a bar | AC-01 | #{sign_in_spec}: \"AC-01 shows \\\"Ada \\| Lovelace\\\" as the name\" |",
      "| A skipped test | AC-01 | #{sign_in_spec}: \"AC-01 is skipped for now\" |"
    )
    run_task("test_mapping:write")
    expect(run_task("test_mapping:check")).to eq([ "Test mapping check passed: specs/docs/test_mapping.md is current.\n", "", 0 ])

    write_spec(
      "backend/spec/requests/sign_in_spec.rb",
      rspec_test("AC-01 signs in with a Google account"),
      rspec_test('AC-01 shows \"Ada | Lovelace\" as the name'),
      rspec_test("AC-01 is skipped for now", keyword: "xit")
    )
    run_task("test_mapping:write")
    expect(run_task("test_mapping:check")).to eq([
      "",
      "Test mapping check failed:\n" \
        "- README.md \"Test coverage\" names a test that does not exist: " \
        "backend/spec/requests/sign_in_spec.rb: \"AC-01 signs in with Google\".\n",
      1
    ])

    readme.call(
      "## Test coverage",
      "| Mark as reviewed | AC-13 | `backend/spec/requests/mark_reviewed_spec.rb`: \"AC-13 marks a note as reviewed\" |"
    )
    expect(run_task("test_mapping:check")[1..]).to eq([
      "Test mapping check failed:\n" \
        "- README.md \"Test coverage\" names a test that does not exist: " \
        "backend/spec/requests/mark_reviewed_spec.rb: \"AC-13 marks a note as reviewed\".\n",
      1
    ])

    write_file("README.md", "# Personal Knowledge Base", "", "## Running locally")
    expect(run_task("test_mapping:check").last).to eq(0)
  end
end
